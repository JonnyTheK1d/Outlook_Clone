import { test, expect } from '@playwright/test';
test.beforeEach(async ({ page }) => { await page.goto('/'); await expect(page.getByRole('heading', { name: 'Posteingang', exact: true })).toBeVisible(); });
test('mail workflow: search, flag, archive, trash and persist', async ({ page }) => {
  await page.getByRole('textbox', { name: 'Suchen', exact: true }).fill('Design-Review');
  await expect(page.locator('.message-item')).toHaveCount(1);
  await page.locator('.message-item').click();
  await expect(page.getByRole('heading', { name: 'Design-Review · Donnerstag' })).toBeVisible();
  await page.getByRole('button', { name: 'Archivieren', exact: true }).click();
  await page.getByRole('button', { name: 'Archiv', exact: true }).click();
  await page.locator('.message-item').click();
  await expect(page.getByRole('heading', { name: 'Design-Review · Donnerstag' })).toBeVisible();
  await page.getByRole('button', { name: 'Löschen', exact: true }).click();
  await page.getByRole('button', { name: 'Papierkorb', exact: true }).click();
  await expect(page.locator('.message-item')).toHaveCount(1);
  await page.reload();
  await page.getByRole('button', { name: 'Papierkorb', exact: true }).click();
  await page.locator('.message-item').click();
  await page.getByRole('button', { name: 'Löschen', exact: true }).click();
  await expect(page.getByRole('dialog', { name: 'Nachricht endgültig löschen?' })).toBeVisible();
  await page.getByRole('button', { name: 'Endgültig löschen', exact: true }).click();
  await expect(page.locator('.message-item')).toHaveCount(0);
});
test('compose, save draft, reopen and send locally', async ({ page }) => {
  await page.getByRole('button', { name: 'Neue E-Mail', exact: true }).click();
  await page.getByRole('textbox', { name: 'Empfänger', exact: true }).fill('test@example.com');
  await page.getByRole('textbox', { name: 'Betreff', exact: true }).fill('Mein erster Entwurf');
  await page.getByRole('textbox', { name: 'Nachrichtentext' }).fill('Hallo aus Postblick!');
  await page.getByRole('button', { name: 'Entwurf speichern' }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByRole('button', { name: /^Entwürfe/ }).click();
  await page.locator('.message-item').click();
  await page.getByRole('button', { name: 'Entwurf bearbeiten' }).click();
  await expect(page.getByRole('textbox', { name: 'Nachrichtentext' })).toHaveValue('Hallo aus Postblick!');
  await page.getByRole('button', { name: 'Lokal senden' }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByRole('button', { name: 'Gesendet', exact: true }).click();
  await expect(page.locator('.message-item').filter({ hasText: 'Mein erster Entwurf' })).toHaveCount(1);
});
