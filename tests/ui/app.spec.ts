test('double-click opens a message window that replies in its own compose window',async({page,context})=>{
  const item=page.locator('.message-item').filter({hasText:'Design-Review'});
  const [reader]=await Promise.all([context.waitForEvent('page'),item.dblclick()]);
  await expect(reader.getByRole('heading',{name:'Design-Review · Donnerstag'})).toBeVisible();
  await expect(reader).toHaveTitle(/Design-Review/);
  const [composer]=await Promise.all([context.waitForEvent('page'),reader.getByRole('button',{name:'Antworten',exact:true}).first().click()]);
  await expect(composer.getByRole('textbox',{name:'Betreff',exact:true})).toHaveValue('Re: Design-Review · Donnerstag');
  await expect(composer.getByRole('combobox',{name:'Empfänger',exact:true})).toHaveValue('daniel@example.com');
  await composer.getByRole('button',{name:'Lokal senden',exact:true}).click();
  await expect.poll(()=>composer.isClosed()).toBe(true);
  await page.getByRole('button',{name:'Gesendet',exact:true}).click();
  await expect(page.locator('.message-item').filter({hasText:'Re: Design-Review'})).toHaveCount(1);
  await reader.keyboard.press('Control+u');
  await expect(page.locator('.message-item.unread')).toHaveCount(0);
  await page.getByRole('button',{name:'Posteingang',exact:true}).first().click();
  await expect(page.locator('.message-item.unread').filter({hasText:'Design-Review'})).toHaveCount(1);
  await Promise.all([reader.waitForEvent('close'),reader.keyboard.press('Delete').catch(()=>{})]);
  await expect(page.locator('.message-item').filter({hasText:'Design-Review'})).toHaveCount(0);
});
